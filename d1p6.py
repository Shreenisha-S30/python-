sentence="The quick brown fox jumps over the lazy dog. The dog is not so lazy after all!"
print(sentence)
print(sentence.lower()) #covert the sentence to lowercase
print(sentence.upper()) #convert the sentence to uppercase

print(sentence.strip()) #remove any leading or trailing whitespace
print(sentence.replace("dog","cat")) #replace dog with cat
print(sentence.title()) #capitalize the first letter of each word in the sentence


